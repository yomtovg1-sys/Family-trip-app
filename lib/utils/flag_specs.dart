/// bitmap-based color-emoji font this app bundles. Plain shapes drawn with
/// [Canvas] have no such dependency: they render identically everywhere.
class FlagSpec {
  final FlagLayout layout;
  final List<Color> colors;
  const FlagSpec(this.layout, this.colors);
}

