/// How a [FlagSpec] paints its colors. Every real-world flag is
/// approximated as the closest of these simple geometric patterns — exact
/// emblems, crescents, and diagonals are dropped, but the flag's dominant
/// colors and overall shape stay recognizable.
enum FlagLayout { solid, horizontalStripes, verticalStripes, nordicCross, centeredCross, disc, canton }

/// A simplified description of a country's flag: a layout plus the colors
/// it uses, in the order [FlagIcon]'s painter expects for that layout.
